@pytest.mark.anyio
async def test_pick_random_movie_frame_source_resolves_a_real_file(tmp_path):
    real_dir = tmp_path / "real_media"
    real_dir.mkdir()
    real_file = real_dir / "movie.mp4"
    real_file.write_bytes(b"fake video bytes")

    db_path = tmp_path / "cache" / "quote_index.db"
    _cache_title(db_path, "guid-1", "1", "A Movie", "Movies")

    media = _FakeMedia(
        movie_library_names=frozenset({"Movies"}),
        movies_by_id={"1": _movie("1", "Movies", "/media/movies/movie.mp4")},
    )
    settings = _settings_with_mapping(tmp_path, "Movies", "/media/movies", real_dir)

    result = await pick_random_movie_frame_source(media, settings, db_path)
    assert result is not None
    movie, container_path = result
    assert movie.media_id == "1"
    assert container_path == str(real_file)


@pytest.mark.anyio
async def test_pick_random_movie_frame_source_skips_a_title_whose_file_is_gone(tmp_path):
    db_path = tmp_path / "cache" / "quote_index.db"
    _cache_title(db_path, "guid-1", "1", "A Movie", "Movies")

    media = _FakeMedia(
        movie_library_names=frozenset({"Movies"}),
        movies_by_id={"1": _movie("1", "Movies", "/media/movies/missing.mp4")},
    )
    # No path mapping at all configured for "Movies" — path_mappings_for
    # raises SettingsError, which must be treated as "this one didn't
    # resolve" rather than propagating and failing the whole pick.
    settings = Settings(discord_token="x", plex_url="http://x", plex_token="x", cache_dir=tmp_path / "cache")

    result = await pick_random_movie_frame_source(media, settings, db_path)
    assert result is None
